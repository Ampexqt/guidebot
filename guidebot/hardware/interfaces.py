"""Small contracts for future drivers; angles are logical degrees, distance is cm."""

from typing import Mapping, Protocol

SERVO_NAMES = ("head_pan", "head_tilt", "left_arm", "right_arm")


class ServoDriver(Protocol):
    @property
    def angles(self) -> Mapping[str, float]: ...
    @property
    def active_gesture(self) -> str: ...
    def gesture(self, name: str) -> None: ...
    def update(self, dt: float) -> None: ...
    def close(self) -> None: ...


class DistanceSensor(Protocol):
    def update(self, dt: float) -> None: ...
    def read_cm(self) -> float: ...
    def close(self) -> None: ...


class DisplayDriver(Protocol):
    """A future display accepts a 240x320 RGB frame supplied by a renderer."""
    def present_rgb(self, pixels: bytes, width: int, height: int) -> None: ...
    def close(self) -> None: ...
